CREATE OR REPLACE PACKAGE PKG_ORDER AS
  FUNCTION  CALC_TAX(P_AMOUNT IN NUMBER) RETURN NUMBER;
  FUNCTION  FORMAT_NAME(P_LAST IN VARCHAR2, P_FIRST IN VARCHAR2) RETURN VARCHAR2;
  FUNCTION  MONTH_END_AFTER(P_DATE IN DATE, P_MONTHS IN NUMBER) RETURN DATE;
  FUNCTION  FIND_CUSTOMER_ID(P_NAME_PREFIX IN VARCHAR2) RETURN NUMBER;
  FUNCTION  TOP_ORDERS(P_N IN NUMBER) RETURN SYS_REFCURSOR;
  PROCEDURE CREATE_ORDER(P_CUSTOMER_ID IN NUMBER, P_AMOUNT IN NUMBER, P_NOTE IN VARCHAR2,
                         P_ORDER_ID OUT NUMBER, P_TAX OUT NUMBER);
  PROCEDURE CHANGE_STATUS(P_ORDER_ID IN NUMBER, P_STATUS IN VARCHAR2);
  PROCEDURE GET_ORDERS(P_CUSTOMER_ID IN NUMBER, P_CUR OUT SYS_REFCURSOR);
END PKG_ORDER;
/
CREATE OR REPLACE PACKAGE BODY PKG_ORDER AS

  FUNCTION CALC_TAX(P_AMOUNT IN NUMBER) RETURN NUMBER IS
  BEGIN
    IF P_AMOUNT IS NULL THEN
      RETURN NULL;
    END IF;
    IF P_AMOUNT < 0 THEN
      RAISE_APPLICATION_ERROR(-20001, 'amount must be >= 0');
    END IF;
    RETURN TRUNC(P_AMOUNT * 0.1);
  END CALC_TAX;

  FUNCTION FORMAT_NAME(P_LAST IN VARCHAR2, P_FIRST IN VARCHAR2) RETURN VARCHAR2 IS
  BEGIN
    RETURN TRIM(P_LAST || ' ' || P_FIRST);
  END FORMAT_NAME;

  FUNCTION MONTH_END_AFTER(P_DATE IN DATE, P_MONTHS IN NUMBER) RETURN DATE IS
  BEGIN
    RETURN LAST_DAY(ADD_MONTHS(P_DATE, P_MONTHS));
  END MONTH_END_AFTER;

  FUNCTION FIND_CUSTOMER_ID(P_NAME_PREFIX IN VARCHAR2) RETURN NUMBER IS
    V_ID CUSTOMERS.ID%TYPE;
  BEGIN
    SELECT ID INTO V_ID FROM CUSTOMERS WHERE NAME LIKE P_NAME_PREFIX || '%';
    RETURN V_ID;
  END FIND_CUSTOMER_ID;

  FUNCTION TOP_ORDERS(P_N IN NUMBER) RETURN SYS_REFCURSOR IS
    V_CUR SYS_REFCURSOR;
  BEGIN
    OPEN V_CUR FOR
      SELECT ID, AMOUNT FROM (SELECT ID, AMOUNT FROM ORDERS ORDER BY AMOUNT DESC, ID)
       WHERE ROWNUM <= P_N;
    RETURN V_CUR;
  END TOP_ORDERS;

  PROCEDURE CREATE_ORDER(P_CUSTOMER_ID IN NUMBER, P_AMOUNT IN NUMBER, P_NOTE IN VARCHAR2,
                         P_ORDER_ID OUT NUMBER, P_TAX OUT NUMBER) IS
  BEGIN
    P_TAX := CALC_TAX(P_AMOUNT);
    P_ORDER_ID := ORDER_SEQ.NEXTVAL;
    INSERT INTO ORDERS (ID, CUSTOMER_ID, AMOUNT, TAX, STATUS, NOTE, ORDER_DATE, UPDATED_AT)
    VALUES (P_ORDER_ID, P_CUSTOMER_ID, P_AMOUNT, P_TAX, 'NEW', P_NOTE, APP_CLOCK.NOW, SYSDATE);
    DBMS_OUTPUT.PUT_LINE('created order ' || P_ORDER_ID);
  END CREATE_ORDER;

  PROCEDURE CHANGE_STATUS(P_ORDER_ID IN NUMBER, P_STATUS IN VARCHAR2) IS
  BEGIN
    UPDATE ORDERS SET STATUS = P_STATUS, UPDATED_AT = SYSDATE WHERE ID = P_ORDER_ID;
    IF SQL%ROWCOUNT = 0 THEN
      RAISE_APPLICATION_ERROR(-20002, 'order not found: ' || P_ORDER_ID);
    END IF;
  END CHANGE_STATUS;

  PROCEDURE GET_ORDERS(P_CUSTOMER_ID IN NUMBER, P_CUR OUT SYS_REFCURSOR) IS
  BEGIN
    OPEN P_CUR FOR
      SELECT ID, AMOUNT, STATUS FROM ORDERS WHERE CUSTOMER_ID = P_CUSTOMER_ID ORDER BY ID;
  END GET_ORDERS;

END PKG_ORDER;
