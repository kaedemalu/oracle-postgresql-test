CREATE TABLE CUSTOMERS (
  ID          NUMBER(10)          CONSTRAINT CUSTOMERS_PK PRIMARY KEY,
  NAME        VARCHAR2(50 CHAR)   NOT NULL,
  RANK        CHAR(1),
  CREATED_AT  DATE
);
/
CREATE TABLE ORDERS (
  ID          NUMBER(10)          CONSTRAINT ORDERS_PK PRIMARY KEY,
  CUSTOMER_ID NUMBER(10)          NOT NULL CONSTRAINT ORDERS_CUSTOMER_FK REFERENCES CUSTOMERS(ID),
  AMOUNT      NUMBER(12,2)        NOT NULL CONSTRAINT ORDERS_AMOUNT_CK CHECK (AMOUNT >= 0),
  TAX         NUMBER(12,2),
  STATUS      VARCHAR2(10)        DEFAULT 'NEW' NOT NULL,
  NOTE        VARCHAR2(100 CHAR),
  ORDER_DATE  DATE,
  UPDATED_AT  DATE
);
/
CREATE TABLE AUDIT_LOG (
  ID          NUMBER(10)          CONSTRAINT AUDIT_LOG_PK PRIMARY KEY,
  ORDER_ID    NUMBER(10),
  ACTION      VARCHAR2(10),
  OLD_STATUS  VARCHAR2(10),
  NEW_STATUS  VARCHAR2(10),
  LOGGED_AT   DATE
);
/
CREATE SEQUENCE ORDER_SEQ START WITH 1 NOCACHE;
/
CREATE SEQUENCE AUDIT_SEQ START WITH 1 NOCACHE;
/
CREATE OR REPLACE VIEW V_CUSTOMER_TOTALS AS
SELECT c.ID, c.NAME, COUNT(o.ID) AS ORDER_COUNT, NVL(SUM(o.AMOUNT), 0) AS TOTAL_AMOUNT
  FROM CUSTOMERS c, ORDERS o
 WHERE o.CUSTOMER_ID (+) = c.ID
 GROUP BY c.ID, c.NAME;
/
