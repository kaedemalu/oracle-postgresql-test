-- 時刻取得ラッパ(仕様 5.6 (b) 方式)。テスト時は SET_FIXED で固定値を注入する
CREATE OR REPLACE PACKAGE APP_CLOCK AS
  PROCEDURE SET_FIXED(P_TS IN DATE);
  PROCEDURE CLEAR;
  FUNCTION NOW RETURN DATE;
END APP_CLOCK;
/
CREATE OR REPLACE PACKAGE BODY APP_CLOCK AS
  G_FIXED DATE;

  PROCEDURE SET_FIXED(P_TS IN DATE) IS
  BEGIN
    G_FIXED := P_TS;
  END;

  PROCEDURE CLEAR IS
  BEGIN
    G_FIXED := NULL;
  END;

  FUNCTION NOW RETURN DATE IS
  BEGIN
    RETURN NVL(G_FIXED, SYSDATE);
  END;
END APP_CLOCK;
/
