CREATE OR REPLACE TRIGGER TRG_ORDERS_AUDIT
AFTER INSERT OR UPDATE OF STATUS ON ORDERS
FOR EACH ROW
DECLARE
  V_ACTION AUDIT_LOG.ACTION%TYPE;
BEGIN
  V_ACTION := CASE WHEN INSERTING THEN 'INSERT' ELSE 'UPDATE' END;
  INSERT INTO AUDIT_LOG (ID, ORDER_ID, ACTION, OLD_STATUS, NEW_STATUS, LOGGED_AT)
  VALUES (AUDIT_SEQ.NEXTVAL, :NEW.ID, V_ACTION, :OLD.STATUS, :NEW.STATUS, APP_CLOCK.NOW);
END;
/
